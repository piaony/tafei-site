create table if not exists public.tafei_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users (id) on delete cascade,
  recipient_id uuid not null references auth.users (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists tafei_messages_sender_idx
  on public.tafei_messages (sender_id, created_at desc);
create index if not exists tafei_messages_recipient_idx
  on public.tafei_messages (recipient_id, created_at desc);

-- 行级安全：默认谁都读不到，只放行以下三种操作
alter table public.tafei_messages enable row level security;

drop policy if exists "tafei_dm_insert" on public.tafei_messages;
create policy "tafei_dm_insert" on public.tafei_messages
  for insert to authenticated
  with check (sender_id = auth.uid());

drop policy if exists "tafei_dm_select" on public.tafei_messages;
create policy "tafei_dm_select" on public.tafei_messages
  for select to authenticated
  using (sender_id = auth.uid() or recipient_id = auth.uid());

drop policy if exists "tafei_dm_update" on public.tafei_messages;
create policy "tafei_dm_update" on public.tafei_messages
  for update to authenticated
  using (recipient_id = auth.uid())
  with check (recipient_id = auth.uid());
grant select, insert, update on public.tafei_messages to authenticated;
